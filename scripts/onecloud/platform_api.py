"""System boundary for the shared receiver supervisor.

get_platform() is the Debian/Armbian adapter (OneCloud, N1), which builds the network itself. OpenWrt
keeps its own network: supervisor_openwrt.py uses platform_openwrt.OpenWrtPlatform explicitly, which
only reads it. Never pick an adapter by distro detection.
"""
from typing import Protocol


class Platform(Protocol):
    children: list
    ap_vif: str          # name of the box-hotspot interface created beside a car-hotspot client
    ap_interface: str    # where the box hotspot runs now: the Wi-Fi interface or ap_vif

    def configure_hotspot(self, channel, width, ssid, passphrase): ...
    def set_ap_address(self, address): ...
    def start_ap(self, wait_for): ...
    def start_dhcp(self, address, portal, names=()): ...
    def join_wifi(self, car, lease, wait_for, seconds): ...
    def join_log(self): ...
    def remove_sta_network(self): ...
    def flush_address(self): ...
    def connected(self): ...
    def frequency(self): ...
    def ipv4_address(self): ...
    def security(self, ssid): ...
    def has_stations(self): ...
    def scan_networks(self, own_ssid, ap=False): ...
    def find_hotspot(self, ssid, frequency=None): ...
    def local_addresses(self): ...
    def wifi_interface(self): ...
    def start(self, name, argv): ...
    def stop_child(self, name): ...
    def stop_all(self): ...
    def power_bluetooth(self): ...
    def status_light(self): ...
    def prepare(self, wait_for): ...
    def allow_nonlocal_bind(self): ...
    def boot_id(self): ...
    def diagnostics(self): ...
    def concurrent_ap(self): ...
    def add_ap_interface(self): ...
    def disconnect(self): ...
    def quick_ack(self): ...
    def reassociate(self, wait_for, seconds=20): ...
    def remove_ap_interface(self): ...


def get_platform(interface="", **paths) -> Platform:
    from platform_debian import DebianPlatform
    return DebianPlatform(interface, **paths)
